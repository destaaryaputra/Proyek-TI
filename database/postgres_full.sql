-- 1. DROP TABLES (Reverse order to avoid FK errors)
DROP TABLE IF EXISTS tabel_notifikasi CASCADE;
DROP TABLE IF EXISTS tabel_password_reset_tokens CASCADE;
DROP TABLE IF EXISTS tabel_rate_limits CASCADE;
DROP TABLE IF EXISTS tabel_nilai CASCADE;
DROP TABLE IF EXISTS tabel_kehadiran CASCADE;
DROP TABLE IF EXISTS tabel_jadwal CASCADE;
DROP TABLE IF EXISTS tabel_siswa CASCADE;
DROP TABLE IF EXISTS tabel_guru CASCADE;
DROP TABLE IF EXISTS tabel_admin CASCADE;
DROP TABLE IF EXISTS tabel_mapel CASCADE;
DROP TABLE IF EXISTS tabel_kelas CASCADE;
DROP TABLE IF EXISTS tabel_users CASCADE;

-- 2. CREATE TABLES

CREATE TABLE tabel_users (
    id_user SERIAL PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('admin', 'guru', 'siswa')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tabel_admin (
    id_admin SERIAL PRIMARY KEY,
    id_user INT NOT NULL UNIQUE,
    nama VARCHAR(100) NOT NULL,
    email VARCHAR(100) NULL,
    FOREIGN KEY (id_user) REFERENCES tabel_users(id_user) ON DELETE CASCADE
);

CREATE TABLE tabel_guru (
    id_guru SERIAL PRIMARY KEY,
    id_user INT NOT NULL UNIQUE,
    nama VARCHAR(100) NOT NULL UNIQUE,
    jenis_kelamin VARCHAR(1) NULL CHECK (jenis_kelamin IN ('L', 'P')),
    email VARCHAR(100) NULL,
    FOREIGN KEY (id_user) REFERENCES tabel_users(id_user) ON DELETE CASCADE
);

CREATE TABLE tabel_kelas (
    id_kelas SERIAL PRIMARY KEY,
    nama_kelas VARCHAR(30) NOT NULL,
    tingkat VARCHAR(2) NOT NULL CHECK (tingkat IN ('7', '8', '9', '10', '11', '12'))
);

CREATE TABLE tabel_mapel (
    id_mapel SERIAL PRIMARY KEY,
    nama_mapel VARCHAR(100) NOT NULL
);

CREATE TABLE tabel_siswa (
    id_siswa SERIAL PRIMARY KEY,
    id_user INT NOT NULL UNIQUE,
    id_kelas INT NULL,
    nama VARCHAR(100) NOT NULL UNIQUE,
    jenis_kelamin VARCHAR(1) NULL CHECK (jenis_kelamin IN ('L', 'P')),
    nis VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(100) NULL,
    FOREIGN KEY (id_user) REFERENCES tabel_users(id_user) ON DELETE CASCADE,
    FOREIGN KEY (id_kelas) REFERENCES tabel_kelas(id_kelas) ON DELETE SET NULL
);

CREATE TABLE tabel_jadwal (
    id_jadwal SERIAL PRIMARY KEY,
    id_guru INT NOT NULL,
    id_kelas INT NOT NULL,
    id_mapel INT NOT NULL,
    hari VARCHAR(10) NOT NULL CHECK (hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu')),
    jam VARCHAR(20) NOT NULL,
    FOREIGN KEY (id_guru) REFERENCES tabel_guru(id_guru) ON DELETE CASCADE,
    FOREIGN KEY (id_kelas) REFERENCES tabel_kelas(id_kelas) ON DELETE CASCADE,
    FOREIGN KEY (id_mapel) REFERENCES tabel_mapel(id_mapel) ON DELETE CASCADE
);

CREATE TABLE tabel_kehadiran (
    id_kehadiran SERIAL PRIMARY KEY,
    id_siswa INT NOT NULL,
    id_guru INT NOT NULL,
    id_mapel INT NOT NULL,
    tanggal DATE NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('hadir', 'izin', 'sakit', 'alpa')),
    CONSTRAINT uk_kehadiran_siswa_tanggal_mapel UNIQUE (id_siswa, tanggal, id_mapel),
    FOREIGN KEY (id_siswa) REFERENCES tabel_siswa(id_siswa) ON DELETE CASCADE,
    FOREIGN KEY (id_guru) REFERENCES tabel_guru(id_guru) ON DELETE CASCADE,
    FOREIGN KEY (id_mapel) REFERENCES tabel_mapel(id_mapel) ON DELETE CASCADE
);

CREATE TABLE tabel_nilai (
    id_nilai SERIAL PRIMARY KEY,
    id_siswa INT NOT NULL,
    id_mapel INT NOT NULL,
    id_guru INT NOT NULL,
    jenis_penilaian VARCHAR(10) NOT NULL CHECK (jenis_penilaian IN ('tugas', 'kuis', 'uts', 'uas')),
    skor DECIMAL(5,2) NOT NULL,
    periode VARCHAR(30) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_nilai_unique UNIQUE (id_siswa, id_mapel, jenis_penilaian, periode),
    FOREIGN KEY (id_siswa) REFERENCES tabel_siswa(id_siswa) ON DELETE CASCADE,
    FOREIGN KEY (id_mapel) REFERENCES tabel_mapel(id_mapel) ON DELETE CASCADE,
    FOREIGN KEY (id_guru) REFERENCES tabel_guru(id_guru) ON DELETE CASCADE
);

CREATE TABLE tabel_notifikasi (
    id_notifikasi SERIAL PRIMARY KEY,
    id_user INT NOT NULL,
    pesan VARCHAR(255) NOT NULL,
    tanggal DATE NOT NULL,
    dibaca BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_user) REFERENCES tabel_users(id_user) ON DELETE CASCADE
);

CREATE TABLE tabel_password_reset_tokens (
    id_reset BIGSERIAL PRIMARY KEY,
    id_user INT NOT NULL,
    email VARCHAR(100) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_user) REFERENCES tabel_users(id_user) ON DELETE CASCADE
);
CREATE INDEX idx_reset_user ON tabel_password_reset_tokens (id_user);
CREATE INDEX idx_reset_expires ON tabel_password_reset_tokens (expires_at);

CREATE TABLE tabel_rate_limits (
    key_hash CHAR(64) PRIMARY KEY,
    bucket_label VARCHAR(64) NOT NULL,
    attempts_json TEXT NOT NULL,
    blocked_until TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rate_limit_blocked_until ON tabel_rate_limits (blocked_until);

